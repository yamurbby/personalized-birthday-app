const ORDER = ['seahorse', 'octopus', 'jellyfish', 'clownfish', 'legend', 'bottle', 'can', 'letter'];
const COLS = 8, T = 16;
const buf = Buffer.alloc(COLS * T * T * 4);
ORDER.forEach((name, idx) => {
  const rows = SPRITES[name].trim().split('\n').map((r) => r.trim());
  rows.forEach((row, y) => {
    [...row.padEnd(T, '.')].slice(0, T).forEach((ch, x) => {
      const hex = PAL[ch];
      if (!hex) return;
      const o = (y * COLS * T + idx * T + x) * 4;
      buf[o] = parseInt(hex.slice(1, 3), 16); buf[o + 1] = parseInt(hex.slice(3, 5), 16); buf[o + 2] = parseInt(hex.slice(5, 7), 16); buf[o + 3] = 255;
    });
  });
});
mkdirSync('src/assets/fish', { recursive: true });
await sharp(buf, { raw: { width: COLS * T, height: T, channels: 4 } }).png().toFile('src/assets/fish/extra.png');
